"""NumPy models of geglu_epilogue.cc's GeGLU modes, op for op, for the CPU-emulation gate and the device check.

    geglu(g, u, mode)   g, u fp32 (the accumulator's gate and up values) -> fp32 [same shape]

mode 1 (fp32): gelu_tanh(g) * u in fp32 arithmetic; on device it matches fp64 to ~3e-7 of the row max, so it is
    modelled as exact.
mode 2 (bf16): native bf16 products with fp32 accumulation, every product rounded to bf16 (nearest even) where the
    kernel rounds it:
        gb = bf16(g)
        c  = bf16(bf16(gb * gb) * bf16(0.044715))                        0.044715 g^2
        w  = g + gb * c                                                  fp32 accumulate: g + 0.044715 g^3
        zq = round(bf16(w) * bf16(256 * 2 sqrt(2/pi)))                   z = 2 sqrt(2/pi) w, fixed point x 256
        e  = bf16(ILUT[(d >> 8) & 255] * FLUT[d & 255]),  d = max(-|zq|, -80 * 256)    e^(-|z|), v5's tables
        den = bf16(1 + e);  y0 = magic seed of den;  two steps y <- bf16(y * bf16(2 - den * y))    1 / (1 + e)
        s  = y where zq >= 0, else bf16(e * y)                           sigmoid(z)
        out = bf16(gb * s) * bf16(u)                                     exact in fp32, written back unrounded
    (the host rounds it to bf16 as the down product's input, the same rounding a final bf16 here would be).
The CPU-emulation gate of mode 2 with a final bf16 rounding read cos min 0.9999880
(results/aie/embedgemma_geglu_mode2_numerics_cpu_desktop2_*); without it the value is that one rounded later.

    python kernels/embedgemma/geglu_model.py tables     writes geglu_tables.h (the exp tables geglu_epilogue.cc
                                                         includes, the same values attn_local.cc uses)
"""
import sys
from pathlib import Path
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from attention_oracle import _FLUT, _ILUT  # noqa: E402


def bf16(x):
    u = np.ascontiguousarray(x, np.float32).view(np.uint32)
    return ((u + 0x7FFF + ((u >> 16) & 1)) & 0xFFFF0000).view(np.float32)


def gelu_tanh(x):
    x = np.asarray(x, np.float64)
    return 0.5 * x * (1 + np.tanh(np.sqrt(2 / np.pi) * (x + 0.044715 * x ** 3)))


ZSCALE = np.float32(256 * 2 * np.sqrt(2 / np.pi))


def geglu(g, u, mode=2):
    g, u = np.asarray(g, np.float32), np.asarray(u, np.float32)
    if mode == 1:
        return (gelu_tanh(g) * u).astype(np.float32)
    if mode == 5:
        return _geglu_poly(g, u)
    gb = bf16(g)
    c = bf16(bf16(gb * gb) * bf16(np.float32(0.044715)))
    w = (g.astype(np.float64) + gb.astype(np.float64) * c).astype(np.float32)
    zq = np.round((bf16(w) * bf16(ZSCALE)).astype(np.float64)).astype(np.int64)   # product exact in fp32, then round
    d = np.maximum(-np.abs(zq), -80 * 256)
    e = bf16((_ILUT[(d >> 8) & 255] * _FLUT[d & 255]).astype(np.float32))
    den = bf16(np.float32(1) + e)
    y = (np.int32(0x7ef311c3) - den.view(np.int32)).view(np.float32)
    y = bf16(y)
    for _ in range(2):
        y = bf16(y * bf16((np.float64(2) - den.astype(np.float64) * y).astype(np.float32)))
    s = np.where(zq >= 0, y, bf16(e * y))
    return (bf16(gb * s) * bf16(u)).astype(np.float32)


def _mac(c, a, b):
    """accfloat c + a * b: the product of two bf16 values is exact in fp32; one fp32 rounding on the add."""
    return (np.asarray(c, np.float64) + np.asarray(a, np.float64) * np.asarray(b, np.float64)).astype(np.float32)


P3 = (np.float32(0.9999925), np.float32(0.6958160), np.float32(0.2260760), np.float32(0.0781021))   # 2^f on [0, 1)


def _geglu_poly(g, u):
    """mode 5: mode 2 with e^-|z| = 2^n 2^f, 2^f by a degree-3 polynomial in bf16 MACs (no tables)."""
    gb = bf16(g)
    c = bf16(bf16(gb * gb) * bf16(np.float32(0.044715)))
    wb = bf16(_mac(g, gb, c))
    tq = np.round((wb * bf16(np.float32(589.3713))).astype(np.float64)).astype(np.int64)
    d = np.maximum(-np.abs(tq), -100 * 256)
    n = d >> 8
    f = ((d & 255) / 256).astype(np.float32)
    p = bf16(_mac(P3[2], f, bf16(P3[3])))
    p = bf16(_mac(P3[1], p, f))
    pf = _mac(P3[0], p, f)
    e = bf16((pf.view(np.int32) + (n << 23).astype(np.int32)).view(np.float32))
    den = bf16(_mac(np.float32(1), e, np.float32(1)))
    y = bf16((np.int32(0x7ef311c3) - den.view(np.int32)).view(np.float32))
    for _ in range(2):
        y = bf16(y * bf16(_mac(np.float32(2), -den, y)))
    s = np.where(tq >= 0, y, bf16(e * y))
    return (bf16(gb * s) * bf16(u)).astype(np.float32)


def write_tables(path):
    from attn_probe import lut_bank
    il = ", ".join(str(int(x)) for x in lut_bank(_ILUT))
    fl = ", ".join(str(int(x)) for x in lut_bank(_FLUT))
    lines = ["// Generated by kernels/embedgemma/geglu_model.py tables: exp's integer-part and fraction tables as BF16",
             "// bits, [v0..v7, v0..v7] per 16 as aie::lut<4, bfloat16> reads them (attention_oracle._ILUT / _FLUT).",
             "#include <stdint.h>"]
    lines += [f"alignas(32) static uint16_t eggl_{name}_{half}[512] = {{{vals}}};"
              for name, vals in (("ilut", il), ("flut", fl)) for half in ("ab", "cd")]
    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__" and sys.argv[1:] == ["tables"]:
    write_tables(Path(__file__).resolve().parent / "geglu_tables.h")
    print("geglu_tables.h written")

// One core's share of an M=1 bf16 GEMV, y = W x, for the whole-array decoder projection (see design.py), with the two
// ops the decoder fuses into it.
//
// Every object the core receives is OBJ_WORDS long. The first of a call is [x][h][zero pad][header]: x at the front
// and the header in the last HDR_WORDS, so x and h can be DMA'd straight from where earlier calls wrote them and the
// pad + header from a constant region. Each object after it is a weight chunk of 12 outputs x 192 inputs in
// mmul<4,8,4> order, [kstep 24][acc 3][kk 8][n 4]. The 12 outputs are three accumulators of 4; x is replicated into the
// four A rows, so every row of C is the same dot product and row 0 is read out.
//
// Header flags:
//   F_INIT  the residual: each output's accumulator starts at h[row] (h at element H_INIT_OFF of the object) instead
//           of zero, so y = bf16(h + W x) with one rounding
//   F_NORM  RMSNorm folded in: gamma is already in W, and the epilogue scales by r = RSQ[bf16(sum x*x)], the sum over
//           x through the same mmul walk; y = bf16(bf16(acc) * r)
// Without flags: accumulation is fp32 from zero across every chunk of a group, then one round-to-nearest-even to bf16.
#include <aie_api/aie.hpp>
#include <stdint.h>

#include "rsq_table.h"     // RSQ[RSQ_SIZE], RSQ_BASE: generated by design.py from reference.rsq_table()

constexpr int OBJ_WORDS = 1152;
constexpr int HDR_WORDS = 16;
constexpr int KCHUNK = 192;
constexpr int KSTEPS = KCHUNK / 8;
constexpr int TILE = 32;              // one 8x4 B tile of bf16
constexpr int ROWS = 4;               // cores per column
constexpr int GROUP = 12;             // outputs per group

// Header words (the last HDR_WORDS of a call's first object)
enum { H_G = 0, H_Q = 1, H_K = 2, H_N = 3, H_FLAGS = 4, H_INIT_OFF = 5, H_COPY = 6 };
enum { F_INIT = 1, F_NORM = 2 };
// ctl words the core keeps for the call: the header, then r's bits at C_R
enum { C_R = 15 };

static inline uint32_t rne16(uint32_t bits) {           // fp32 bits -> bf16 bits, round to nearest even
    return (bits + 0x7fffu + ((bits >> 16) & 1u)) >> 16;
}

using MM = aie::mmul<4, 8, 4, bfloat16, bfloat16, accfloat>;

// r = RSQ[bf16(sum x*x)], the sum walked 8 at a time from zero exactly like a projection's accumulator.
static uint32_t norm_scale(const bfloat16 *x, int k) {
    MM c(aie::zeros<float, 16>());
    for (int s = 0; s < k; s += 8) {
        auto row = aie::load_v<8>(x + s);
        aie::vector<bfloat16, 32> a, b;
        a.insert<8>(0, row); a.insert<8>(1, row); a.insert<8>(2, row); a.insert<8>(3, row);
        for (int kk = 0; kk < 8; ++kk)
            for (int n = 0; n < 4; ++n)
                b[kk * 4 + n] = row[kk];                   // every column of B is x, so C = x . x everywhere
        c.mac(a, b);
    }
    uint32_t ss = c.to_vector<float>().cast_to<uint32>()[0];
    uint32_t u = rne16(ss);
    // clamp to the table: [1.0, 2^32), bf16 bits 0x3F80 .. 0x4F7F (ss is never negative)
    if (u < RSQ_BASE) u = RSQ_BASE;
    if (u > RSQ_BASE + RSQ_SIZE - 1) u = RSQ_BASE + RSQ_SIZE - 1;
    return RSQ[u - RSQ_BASE];
}

extern "C" {

void gemv_begin(const int32_t *obj, int32_t *x_local, int32_t *ctl, int32_t core) {
    const int32_t *hdr = obj + OBJ_WORDS - HDR_WORDS;
    for (int i = 0; i < HDR_WORDS; i += 16)
        aie::store_v(ctl + i, aie::load_v<16>(hdr + i));
    const int words = hdr[H_COPY] / 2;
    for (int i = 0; i < words; i += 16)
        aie::store_v(x_local + i, aie::load_v<16>(obj + i));
    ctl[C_R] = (hdr[H_FLAGS] & F_NORM) ? norm_scale(reinterpret_cast<const bfloat16 *>(x_local), hdr[H_K]) : 0;
    (void)core;
}

void gemv_chunk(const int32_t *obj, const int32_t *x_local, float *acc, int32_t q, const int32_t *ctl,
                int32_t core, int32_t g) {
    const auto *x = reinterpret_cast<const bfloat16 *>(x_local) + q * KCHUNK;
    const auto *w = reinterpret_cast<const bfloat16 *>(obj);
    aie::vector<float, 16> s0, s1, s2;
    if (q != 0) {
        s0 = aie::load_v<16>(acc); s1 = aie::load_v<16>(acc + 16); s2 = aie::load_v<16>(acc + 32);
    } else if (ctl[H_FLAGS] & F_INIT) {
        // this group's 12 rows of h, each broadcast down its accumulator column (element m*4+n is output n)
        const int n_total = ctl[H_N];
        const int base = (core / ROWS) * (n_total / 4) + g * (ROWS * GROUP) + (core % ROWS) * GROUP;
        const auto *h = reinterpret_cast<const uint16_t *>(x_local) + ctl[H_INIT_OFF] + base;
        aie::vector<uint32, 16> b0, b1, b2;
        for (int m = 0; m < 4; ++m)
            for (int n = 0; n < 4; ++n) {
                b0[m * 4 + n] = uint32_t(h[n]) << 16;
                b1[m * 4 + n] = uint32_t(h[4 + n]) << 16;
                b2[m * 4 + n] = uint32_t(h[8 + n]) << 16;
            }
        s0 = b0.cast_to<float>(); s1 = b1.cast_to<float>(); s2 = b2.cast_to<float>();
    } else {
        s0 = s1 = s2 = aie::zeros<float, 16>();
    }
    MM c0(s0), c1(s1), c2(s2);
    for (int k = 0; k < KSTEPS; ++k) {
        auto row = aie::load_v<8>(x + k * 8);
        aie::vector<bfloat16, 32> a;
        a.insert<8>(0, row); a.insert<8>(1, row);
        a.insert<8>(2, row); a.insert<8>(3, row);
        c0.mac(a, aie::load_v<TILE>(w + k * 3 * TILE));
        c1.mac(a, aie::load_v<TILE>(w + k * 3 * TILE + TILE));
        c2.mac(a, aie::load_v<TILE>(w + k * 3 * TILE + 2 * TILE));
    }
    aie::store_v(acc, c0.to_vector<float>());
    aie::store_v(acc + 16, c1.to_vector<float>());
    aie::store_v(acc + 32, c2.to_vector<float>());
}

// Row 0 of each accumulator, rounded to bf16 on the bits (ties to even) and packed two to a word. With F_NORM each
// rounded value is multiplied by r (bf16 x bf16, exact in fp32) and rounded again.
void gemv_emit(const float *acc, int32_t *out, const int32_t *ctl) {
    const auto *bits = reinterpret_cast<const uint32_t *>(acc);
    alignas(32) uint16_t y[16];
    for (int i = 0; i < 12; ++i)
        y[i] = uint16_t(rne16(bits[(i / 4) * 16 + i % 4]));
    if (ctl[H_FLAGS] & F_NORM) {
        auto v = aie::load_v<16>(reinterpret_cast<const bfloat16 *>(y));
        auto r = aie::broadcast<uint16, 16>(uint16_t(ctl[C_R])).cast_to<bfloat16>();
        auto p = aie::mul(v, r).to_vector<float>().cast_to<uint32>();
        for (int i = 0; i < 12; ++i)
            y[i] = uint16_t(rne16(p[i]));
    }
    for (int i = 0; i < 12; i += 2)
        out[i / 2] = static_cast<int32_t>(uint32_t(y[i]) | (uint32_t(y[i + 1]) << 16));
}

}
